#!/bin/sh
set -eu
cd "$(dirname "$0")/.."
isodo_gen_toolchain="go$(sed -n 's/^go //p' go.mod)"
mkdir -p internal/api/admin internal/api/public
GOTOOLCHAIN="$isodo_gen_toolchain" go run github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.0 \
  -config tools/openapi/oapi-codegen-admin.yaml api/openapi/openapi.yaml
GOTOOLCHAIN="$isodo_gen_toolchain" go run github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.0 \
  -config tools/openapi/oapi-codegen-public.yaml api/openapi/openapi-public.yaml
node_tool_dir="$(pwd)/.tools/node/$(uname -s)-$(uname -m)/openapi"
mkdir -p "$node_tool_dir"
if [ ! -x "$node_tool_dir/node_modules/.bin/orval" ] || \
   ! cmp -s "$node_tool_dir/package.json" tools/openapi/package.json || \
   ! cmp -s "$node_tool_dir/package-lock.json" tools/openapi/package-lock.json; then
  cp tools/openapi/package.json tools/openapi/package-lock.json "$node_tool_dir/"
  npm ci --prefix "$node_tool_dir" --ignore-scripts
fi
(
  cd tools/openapi
  "$node_tool_dir/node_modules/.bin/orval" --config orval.config.mjs
)
python3 - <<'PY'
from pathlib import Path

old_client = Path('app/apps/web/src/api/generated.ts')
if old_client.exists() and 'Generated by orval' in old_client.read_text()[:200]:
    old_client.unlink()

models = Path('app/apps/web/src/api/models')
if models.exists():
    for path in models.glob('*.ts'):
        if 'Generated by orval' in path.read_text()[:200]:
            path.unlink()
    if not any(models.iterdir()):
        models.rmdir()
PY
